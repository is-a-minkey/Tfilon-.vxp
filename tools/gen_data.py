#!/usr/bin/env python3
"""Pack the Tfilon MIDlet's resources into a C source file (compressed text, glyph bitmaps, city table)."""
import os, re, sys, zlib
from PIL import Image, ImageFont, ImageDraw

JAR = sys.argv[1]            # extracted jar directory
SRC = sys.argv[2]            # decompiled g.java (renamed members) for the city table
J   = sys.argv[3]            # decompiled j.java for the alphabet
OUT = sys.argv[4]

# ---------- alphabet / byte mapping ----------
ab = open(os.path.join(JAR, 'ab'), 'rb').read()
jsrc = open(J, encoding='utf-8').read()
m = re.search(r'var_char_arr_a = "((?:[^"\\]|\\.)*)"\.toCharArray', jsrc)
alpha = m.group(1).replace('\\"', '"')
assert len(alpha) == len(ab) == 55, (len(alpha), len(ab))
uni2byte = {ord(alpha[i]): ab[i] for i in range(55)}

def to_internal(s):
    out = bytearray()
    for ch in s:
        o = ord(ch)
        if o in uni2byte: out.append(uni2byte[o])
        elif o < 128: out.append(o)
        else: raise ValueError("unmapped char U+%04X in %r" % (o, s))
    return bytes(out)

glyph_of_byte = [255] * 256
for i in range(55):
    glyph_of_byte[ab[i]] = i          # 0..53 glyph, 54 = '~'

# ---------- text resources ----------
skip_ext = ('.class', '.png', '.PNG', '.MF')
res = []
for name in sorted(os.listdir(JAR)):
    p = os.path.join(JAR, name)
    if not os.path.isfile(p) or name.endswith(skip_ext) or name in ('ab',) or name.startswith('specials'):
        continue
    raw = open(p, 'rb').read()
    co = zlib.compressobj(9, zlib.DEFLATED, -15)
    comp = co.compress(raw) + co.flush()
    res.append((name, raw, comp))
blob = bytearray(); entries = []
for name, raw, comp in res:
    entries.append((name, len(blob), len(comp), len(raw)))
    blob += comp
print("resources: %d  raw=%d  packed=%d  max_raw=%d" % (len(res), sum(len(r[1]) for r in res), len(blob), max(len(r[1]) for r in res)), file=sys.stderr)

# ---------- glyph bitmaps ----------
gl = {}
for f in (1, 2):
    ws, hs, offs, bits = [], [], [], bytearray()
    for i in range(54):
        im = Image.open(os.path.join(JAR, 'letters%d' % f, '%d.PNG' % (i + 1))).convert('RGBA')
        w, h = im.size
        px = im.load()
        offs.append(len(bits)); ws.append(w); hs.append(h)
        for y in range(h):
            row = 0
            for x in range(w):
                r, g, b, a = px[x, y]
                ink = a > 0 and (r + g + b) < 384
                row = (row << 1) | (1 if ink else 0)
            nb = (w + 7) // 8
            row <<= (nb * 8 - w)
            bits += row.to_bytes(nb, 'big')
    gl[f] = (ws, hs, offs, bits)

# ---------- ASCII 8x16 bitmap font (for digits/Latin, which the Hebrew glyph set lacks) ----------
afont = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf', 13)
asc = []
for code in range(32, 127):
    im = Image.new('L', (8, 16), 0)
    ImageDraw.Draw(im).text((0, 0), chr(code), font=afont, fill=255)
    px = im.load(); rows = []
    for y in range(16):
        v = 0
        for x in range(8): v = (v << 1) | (1 if px[x, y] > 100 else 0)
        rows.append(v)
    asc.append(rows)

# ---------- cities ----------
g = open(SRC, encoding='utf-8').read()
pat = re.compile(r'(\d+), new int\[\]\{([^}]*)\}, new int\[\]\{([^}]*)\}, "((?:[^"\\]|\\.)*)", (-?\d+), (true|false), ([-0-9.E]+), (-?\d+)\)')
cities = []
for part in g.split('new b(')[1:]:
    mm = pat.match(part)
    cid, lat, lon, name, cand, israel, tz, elev = mm.groups()
    name = re.sub(r'\\u([0-9a-fA-F]{4})', lambda x: chr(int(x.group(1), 16)), name).replace('\\"', '"')
    cities.append((int(cid), [int(x) for x in lat.split(',')], [int(x) for x in lon.split(',')], name, int(cand), israel == 'true', float(tz), int(elev)))
assert len(cities) == 120

def cstr(b):
    return '"' + ''.join('\\%03o' % c for c in b) + '"'

with open(OUT, 'w') as o:
    o.write('/* AUTO-GENERATED by tools/gen_data.py from the original Tfilon.jar - do not edit */\n#include "data.h"\n\n')
    o.write('const unsigned short g_ab_uni[55] = {%s};\n' % ','.join(str(ord(c)) for c in alpha))
    o.write('const unsigned char g_ab_byte[55] = {%s};\n' % ','.join(str(b) for b in ab))
    o.write('const unsigned char g_glyph_of_byte[256] = {%s};\n\n' % ','.join(str(x) for x in glyph_of_byte))
    for f in (1, 2):
        ws, hs, offs, bits = gl[f]
        o.write('const unsigned char g_gl%d_w[54] = {%s};\n' % (f, ','.join(map(str, ws))))
        o.write('const unsigned char g_gl%d_h[54] = {%s};\n' % (f, ','.join(map(str, hs))))
        o.write('const unsigned short g_gl%d_off[54] = {%s};\n' % (f, ','.join(map(str, offs))))
        o.write('const unsigned char g_gl%d_bits[%d] = {%s};\n\n' % (f, len(bits), ','.join(map(str, bits))))
    o.write('const unsigned char g_asc[95][16] = {%s};\n\n' % ','.join('{' + ','.join(map(str, r)) + '}' for r in asc))
    o.write('const City g_cities[%d] = {\n' % len(cities))
    for (cid, lat, lon, name, cand, israel, tz, elev) in cities:
        o.write('  {%d,{%s},{%s},%s,%d,%d,%d,%d},\n' % (cid, ','.join(map(str, lat)), ','.join(map(str, lon)), cstr(to_internal(name)), cand, 1 if israel else 0, int(round(tz * 60)), elev))
    o.write('};\nconst int g_ncities = %d;\n\n' % len(cities))
    o.write('const ResEntry g_res[%d] = {\n' % len(entries))
    for (name, off, clen, rlen) in entries:
        o.write('  {"%s",%d,%d,%d},\n' % (name, off, clen, rlen))
    o.write('};\nconst int g_nres = %d;\n\n' % len(entries))
    o.write('const unsigned char g_blob[%d] = {\n' % len(blob))
    for i in range(0, len(blob), 32):
        o.write(','.join(str(b) for b in blob[i:i+32]) + ',\n')
    o.write('};\n')
print("wrote", OUT, os.path.getsize(OUT), "bytes of C source", file=sys.stderr)
